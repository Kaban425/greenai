def test_rules():
    bad = [(n, want, classify_layer(n)) for n, want in CASES
           if classify_layer(n) != want]
    assert not bad, "\n".join(f"{n!r}: ждали {w}, получили {g}"
                              for n, w, g in bad)


def test_xref_part_takes_tail_only():
    # название улицы в начале имени ссылки на правила не влияет
    assert xref_part("link_Газовый переулок_Люки$0$СЕТИ") == "Люки"
    assert classify_layer("link_Газовый переулок_Прочее$0$СЕТИ") == "unknown"
    # хвост-топоним в правилах не участвует: «деревня» — не деревья
    assert classify_layer("10000176_Олимпийская деревня|ГП 300 300") == "road"
    assert classify_layer("10000176_Олимпийская деревня|$$Оформление") == "annotation"
    assert classify_layer("10000176_Олимпийская деревня|Непонятное") == "unknown"


def test_color_only_on_anonymous_layers():
    cls, src = classify_with_source(["0@@#ff0000",
                                     "Непонятный слой@@#ff0000",
                                     "ДВ_АКР_Границы_слоев@@#ff0000"])
    assert (cls["0@@#ff0000"], src["0@@#ff0000"]) == ("heating", "color")
    assert cls["Непонятный слой@@#ff0000"] == "unknown"
    assert cls["ДВ_АКР_Границы_слоев@@#ff0000"] == "annotation"


