# Имя внешней ссылки Мосгоргеотреста говорит о типе файла:
#   tp — топоплан (ситуация), up — подземные коммуникации,
#   pp — проектируемые сети, brd — рамки листов заказа,
#   kl — линии градостроительного регулирования.
# Это работает на любой улице, а не только на той, где правило написано.
XREF_HINT = [
    (re.compile(r"_brd\$|\bbrd\$0\$"), "annotation"),
    (re.compile(r"\d{4,}up\$|\bup\$0\$"), "utility"),
    (re.compile(r"\d{4,}pp\$|\bpp\$0\$"), "utility"),
    (re.compile(r"\d{4,}kl\$|\bkl\$0\$"), "annotation"),
]


def classify_by_xref(name: str):
    """Класс по имени внешней ссылки, когда имя самого слоя не помогло."""
    for rx, cls in XREF_HINT:
        if rx.search(name):
            return cls
    return None


XREF_PART = re.compile(r"^(.*?)(?:\$\d+\$|\|)")
TOPONYM = re.compile(r"улиц|\bул\b|проспект|переул|деревн|площад|шоссе|"
                     r"набережн|проезд|пр-д|бульвар|район|тупик|аллея\b|"
                     r"^\d|[а-яё]+ская\b|[а-яё]+ский\b", re.IGNORECASE)


def xref_part(name: str) -> str:
    """Последняя часть имени файла подосновы: «link_улица X_Люки$0$СЕТИ» -> «Люки».

    Берётся только хвост после последнего подчёркивания: в начале имени
    стоит название улицы, а оно («Газовый переулок», «Школьная улица»)
    сработало бы на правила как сеть или школа.
    """
    m = XREF_PART.match(split_color(name)[0])
    if not m:
        return ""
    part = normalize(m.group(1).rsplit("_", 1)[-1])
    # Хвост бывает названием места: «10000176_Олимпийская деревня» — и
    # «деревня» по корню «дерев» делала деревьями все слои подосновы.
    return "" if TOPONYM.search(part) else part


def classify_layer(name: str) -> str:
    """Имя слоя -> класс объекта или 'unknown'."""
    clean = normalize(name)
    for cls, rx in COMPILED:
        if rx.search(clean):
            return cls
    hint = classify_by_xref(name)
    if hint:
        return hint
    # Сам слой назван невнятно («СЕТИ»), но файл подосновы подписан:
    # «..._Люки$0$СЕТИ» — это люки.
    part = xref_part(name)
    if part:
        for cls, rx in COMPILED:
            if rx.search(part):
                return cls
    return "unknown"


# Имя, которое ничего не говорит о содержимом: «0», «Слой1», «Layer 3».
# Только на таких слоях цвет линии — признак: на слое с осмысленным
# именем цвет выбран оформителем, и «ГП_PIKETS» красного цвета
# превращался в теплосеть длиной в километр.
ANONYMOUS = re.compile(r"^(0|\d+|слой\s*\d*|layer\s*\d*|new\s*layer\s*\d*|"
                       r"без\s+имени|новый\s+слой\s*\d*)$", re.IGNORECASE)


def is_anonymous(name: str) -> bool:
    return bool(ANONYMOUS.match(normalize(name)))


