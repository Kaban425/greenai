def load_overrides(path):
    """Ручное сопоставление слоёв классам.

    Имена слоёв у каждого проектировщика свои, а на слое «0» вообще нет
    подсказки. Поэтому назначение, сделанное человеком, имеет приоритет
    над правилами и хранится в файле рядом с проектом.
    """
    try:
        import yaml
        with open(path, encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}
        return {str(k): str(v) for k, v in (data.get("layers") or {}).items()
                if str(v) in ASSIGNABLE_CODES}
    except FileNotFoundError:
        return {}
    except Exception:
        return {}


def save_overrides(path, mapping):
    import yaml
    clean = {k: v for k, v in mapping.items() if v in ASSIGNABLE_CODES}
    with open(path, "w", encoding="utf-8") as f:
        yaml.safe_dump({"layers": clean}, f, allow_unicode=True,
                       sort_keys=True, width=120)
    return len(clean)


def classify_with_source(layer_names, overrides=None):
    """Как classify_all, но дополнительно возвращает, чем определён класс.

    Источники: manual — назначено человеком; rules — правило по имени;
    color — цвет линии; unknown — не определено. Модель помечается позже,
    в main.py. Нужно, чтобы вклад каждого механизма был виден цифрами.
    """
    ov = overrides or {}
    cls_map, src_map = {}, {}
    for name in layer_names:
        cls = ov.get(name) or ov.get(normalize(name))
        if cls:
            cls_map[name], src_map[name] = cls, "manual"
            continue
        cls = classify_layer(name)
        if cls != "unknown":
            cls_map[name], src_map[name] = cls, "rules"
            continue
        _, rgb = split_color(name)
        by_color = classify_color(rgb) if is_anonymous(name) else None
        if by_color:
            cls_map[name], src_map[name] = by_color, "color"
        else:
            cls_map[name], src_map[name] = "unknown", "unknown"
    return cls_map, src_map


def classify_all(layer_names, overrides=None):
    """Список имён слоёв -> {имя: класс}. Ручное назначение имеет приоритет."""
    return classify_with_source(layer_names, overrides)[0]
