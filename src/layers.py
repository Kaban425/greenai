"""Классификация слоёв DXF под систему обозначений Мосгоргеотреста.

Коды сетей на инженерно-топографических планах Москвы:
    В1, В2    — водопровод, водовод
    К1        — канализация хозяйственно-бытовая
    К2        — водосток (ливневая канализация)
    Т1, Т2    — тепловая сеть
    Г         — газопровод
    КЛС       — кабель линии связи
    КЭ, КЛ    — кабель электрический
    ДК        — дождеприёмный колодец
    ГНБ       — горизонтально направленное бурение

Нераспознанные слои НЕ участвуют в ограничениях и перечисляются в отчёте.
"""
import re

# Слои подосновы приходят через внешние ссылки (xref) и получают префикс
# вида "link_улица Берзарина_борта$0$". Для классификации он не нужен.
XREF_PREFIX = re.compile(r"^.*?\$\d+\$|^.*?\|")


# "Газон У за счет АБ_ТР" — газон взамен разобранного асфальта тротуара;
# "Тип3 У ПЧ за счет газона" — наоборот, асфальт взамен газона. Значимо то,
# что устраивается, поэтому всё после "за счёт" отбрасываем.
AT_EXPENSE = re.compile(r"\s*за\s+сч[её]т\b.*$", re.IGNORECASE)

# Слои, пришедшие из PDF: «Новый_Асфальт_Ном._пера__94». Префикс и номер
# пера смысла не несут, объект — в середине имени.
PDF_PEN = re.compile(r"^новый[_ ]+|[_ ]+ном\.?[_ ]*пера[_ ]*\d*$", re.IGNORECASE)


FILL_SUFFIX = "__FILL"
COLOR_SEP = "@@"

# Цветовые обозначения инженерных сетей на топографических планах.
# Второй признак после имени слоя: имена у каждой организации свои,
# а цвет держится — им и распознаём слои с невнятными именами.
COLOR_CLASSES = {
    # Цвета сетей на топопланах плюс их ближайшие индексы AutoCAD (ACI):
    # 2 жёлтый, 5 синий, 1 красный, 6 пурпурный, 3 зелёный, 34 коричневый.
    "gas":         [(255, 255, 0), (255, 200, 0), (230, 230, 40)],
    "water":       [(0, 0, 255), (0, 120, 255), (30, 144, 255), (0, 191, 255)],
    "heating":     [(255, 0, 0), (220, 20, 60), (200, 40, 40)],
    "power_cable": [(255, 0, 255), (160, 32, 240), (148, 0, 211), (189, 0, 189)],
    "sewer":       [(139, 69, 19), (160, 82, 45), (120, 72, 40), (153, 76, 0)],
    "existing_tree": [(0, 128, 0), (34, 139, 34), (0, 255, 0), (0, 153, 0)],
}
COLOR_TOLERANCE = 60          # максимальное расстояние в RGB


def split_color(name):
    """Имя слоя вида «Водопровод@@#0000ff» -> (имя, цвет или None)."""
    base, sep, rest = name.partition(COLOR_SEP)
    if not sep:
        return name, None
    rgb = rest.replace(FILL_SUFFIX, "")
    if len(rgb) == 7 and rgb.startswith("#"):
        try:
            return (base + (FILL_SUFFIX if name.endswith(FILL_SUFFIX) else ""),
                    (int(rgb[1:3], 16), int(rgb[3:5], 16), int(rgb[5:7], 16)))
        except ValueError:
            pass
    return base, None


def classify_color(rgb):
    """Класс по цвету линии. None, если цвет ни на что не похож."""
    if rgb is None:
        return None
    r, g, b = rgb
    if max(rgb) - min(rgb) < 40:          # серый, чёрный, белый — не признак
        return None
    best, best_d = None, COLOR_TOLERANCE
    for cls, refs in COLOR_CLASSES.items():
        for rr, gg, bb in refs:
            d = ((r - rr) ** 2 + (g - gg) ** 2 + (b - bb) ** 2) ** 0.5
            if d < best_d:
                best, best_d = cls, d
    return best


def is_filled(name: str) -> bool:
    """Слой закрашенных областей, пришедший из PDF."""
    return name.endswith(FILL_SUFFIX)


def normalize(name: str) -> str:
    """Убирает префикс внешней ссылки, метку цвета и приводит имя к виду."""
    s, _ = split_color(name)
    s = s[:-len(FILL_SUFFIX)] if s.endswith(FILL_SUFFIX) else s
    s = XREF_PREFIX.sub("", s)
    s = AT_EXPENSE.sub("", s)
    s = PDF_PEN.sub("", s)
    s = s.replace("_", " ").replace("-", " ").replace(".", ". ")
    return re.sub(r"\s+", " ", s).strip()


